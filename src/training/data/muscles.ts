export const MUSCLE_BY_ID: Record<string, Muscle> = Object.fromEntries(
  MUSCLES.map((m) => [m.id, m]),
)

export function getMuscle(id: string): Muscle | undefined {
  return MUSCLE_BY_ID[id]
}

/** Display name for a muscle id, falling back to the raw id if unknown. */
export function muscleName(id: string): string {
  return MUSCLE_BY_ID[id]?.name ?? id
}

/** All distinct muscle groups, in the order they first appear. */
export function muscleGroups(): string[] {
  const seen: string[] = []
  for (const m of MUSCLES) if (!seen.includes(m.group)) seen.push(m.group)
  return seen
}
